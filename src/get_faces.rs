use core::array::IntoIter;

#[derive(Debug, Clone, Copy)]
pub struct Point {
    pub x: i32,
    pub y: i32,
}

#[derive(Debug, Clone, Copy)]
pub struct PointMap {
    pub a: Point,
    pub b: Point,
    pub c: Point,
    pub d: Point,
    pub e: Point,
    pub f: Point,
    pub g: Point,
    pub h: Point,
    pub i: Point,
    pub j: Point,
    pub k: Point,
    pub l: Point,
    pub m: Point,
    pub n: Point,
    pub o: Point,
    pub p: Point,
    pub q: Point,
    pub r: Point,
}

// Allow iterating over a PointMap to yield key/value pairs.
impl<'a> IntoIterator for &'a PointMap {
    type Item = (&'static str, &'a Point);
    type IntoIter = IntoIter<(&'static str, &'a Point), 18>;

    fn into_iter(self) -> Self::IntoIter {
        [
            ("a", &self.a),
            ("b", &self.b),
            ("c", &self.c),
            ("d", &self.d),
            ("e", &self.e),
            ("f", &self.f),
            ("g", &self.g),
            ("h", &self.h),
            ("i", &self.i),
            ("j", &self.j),
            ("k", &self.k),
            ("l", &self.l),
            ("m", &self.m),
            ("n", &self.n),
            ("o", &self.o),
            ("p", &self.p),
            ("q", &self.q),
            ("r", &self.r),
        ]
        .into_iter()
    }
}

